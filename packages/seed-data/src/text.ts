import { pick } from './prng.ts'
import type { Prng } from './prng.ts'

const COMMENT_BODIES = [
  'Согласен, особенно с последним абзацем.',
  'Было бы интересно увидеть ещё один пример.',
  'Спасибо, как раз думал об этом на прошлой неделе.',
  'А как это выглядит в другой сезон?',
  'Хороший текст, поделюсь с друзьями.',
  'Не уверен насчёт последней мысли.',
  'Добавил бы пару слов про то, чем всё кончилось.',
  'Любопытный взгляд, раньше так не думал.',
]

export function commentBody(random: Prng): string {
  return pick(random, COMMENT_BODIES)
}
