import { int, pick } from './prng.ts'
import type { Prng } from './prng.ts'

const SUBJECTS = [
  'Хороший интерфейс', 'Надёжная система', 'Небольшая команда', 'Понятный текст', 'Продуманный процесс',
  'Редкая ошибка', 'Простое решение', 'Ранний прототип', 'Честная метрика', 'Общий язык',
]
const PREDICATES = [
  'начинается с наблюдения за людьми', 'прячет сложность за аккуратными границами', 'выигрывает от небольших шагов',
  'ломается там, где его не ждали', 'требует договорённостей до первой строки кода', 'проверяется на реальных данных',
  'легче объяснить на примере, чем в теории', 'становится дороже с каждым неудачным допущением',
  'держится на привычках, а не на инструкциях', 'заметна только тем, кто смотрит внимательно',
]
const TAILS = [
  'и это хорошо видно на практике.', 'особенно когда времени мало.', 'но об этом редко говорят вслух.',
  'и именно поэтому стоит остановиться.', 'если не торопиться с выводами.', 'а дальше всё зависит от контекста.',
]

export function sentence(random: Prng): string {
  return `${pick(random, SUBJECTS)} ${pick(random, PREDICATES)} ${pick(random, TAILS)}`
}

/** Абзац из `count` предложений; детерминирован при том же генераторе. */
export function paragraph(random: Prng, count = int(random, 2, 4)): string {
  return Array.from({ length: count }, () => sentence(random)).join(' ')
}

const TITLE_HEADS = ['Как', 'Почему', 'Когда', 'Зачем']
const TITLE_MIDS = ['мы выбираем простое', 'ломаются планы', 'стоит остановиться', 'нужны границы', 'работает прототип', 'важны мелочи']
const TITLE_TAILS = ['в небольшой команде', 'на практике', 'и что с этим делать', 'без лишних слов', 'на третий месяц']

export function title(random: Prng): string {
  return `${pick(random, TITLE_HEADS)} ${pick(random, TITLE_MIDS)} ${pick(random, TITLE_TAILS)}`
}

const COMMENT_BODIES = [
  'Согласен, особенно про границы.', 'Было бы интересно увидеть пример.', 'Спасибо, как раз с этим столкнулся на прошлой неделе.',
  'А как это работает при большой нагрузке?', 'Хороший текст, поделюсь с командой.', 'Не уверен насчёт последнего абзаца.',
  'Добавил бы пару слов про тестирование.', 'Любопытный взгляд, раньше так не думал.',
]

export function commentBody(random: Prng): string {
  return pick(random, COMMENT_BODIES)
}
