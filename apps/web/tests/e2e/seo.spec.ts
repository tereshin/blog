import { expect, test } from '@playwright/test'

test('метаданные соответствуют маршруту, обновляются при переходе и возврате', async ({ page }) => {
  await page.goto('/p/statya-1?utm_source=test')
  await expect(page).toHaveTitle(/Статья 1/)
  await expect(page.locator('head link[rel="canonical"]')).toHaveAttribute('href', /\/p\/statya-1$/)
  expect(JSON.parse(await page.locator('head script[type="application/ld+json"]').textContent() ?? '{}')['@graph'][0]['@type']).toBe('BlogPosting')
  if ((page.viewportSize()?.width ?? 1280) < 768) await page.getByRole('button', { name: 'Открыть навигацию' }).click()
  await page.getByRole('link', { name: 'Популярное', exact: true }).first().click()
  await expect(page).toHaveTitle('Популярное')
  await expect(page.locator('head meta[property="og:type"]')).toHaveAttribute('content', 'website')
  await expect(page.locator('head meta[name="robots"]')).toHaveAttribute('content', 'noindex, follow')
  await page.goBack()
  await expect(page).toHaveTitle(/Статья 1/)
  await expect(page.locator('head meta[name="description"]')).toHaveCount(1)
  await expect(page.locator('head script[type="application/ld+json"]')).toHaveCount(1)
})

test('автор сохраняет SEO черновика; суперадминистратор сохраняет SEO сайта', async ({ page }) => {
  test.setTimeout(90_000)
  await page.addInitScript(() => { if (!window.localStorage.getItem('mock_viewer')) window.localStorage.setItem('mock_viewer', 'member') })
  await page.goto('/write')
  await expect(page.locator('[data-editor="ready"]')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('textbox', { name: 'Заголовок', exact: true }).fill('Видимый заголовок')
  await page.getByRole('button', { name: 'Параметры статьи' }).click()
  await page.getByRole('textbox', { name: 'SEO-заголовок', exact: true }).fill('Заголовок для поиска')
  await page.getByRole('textbox', { name: 'SEO-описание', exact: true }).fill('Описание для поиска')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page).toHaveURL(/\/write\/[0-9a-f-]{36}$/)
  await page.reload()
  await expect(page.locator('[data-editor="ready"]')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Параметры статьи' }).click()
  await expect(page.getByRole('textbox', { name: 'SEO-заголовок', exact: true })).toHaveValue('Заголовок для поиска')
  await expect(page.getByRole('textbox', { name: 'SEO-описание', exact: true })).toHaveValue('Описание для поиска')
  await page.evaluate(() => window.localStorage.setItem('mock_viewer', 'superadmin'))
  await page.goto('/admin/settings/seo')
  await expect(page.getByRole('heading', { name: 'SEO', exact: true })).toBeVisible()
  const seo = page.getByRole('group', { name: 'SEO', exact: true })
  await seo.getByRole('textbox', { name: 'SEO-заголовок', exact: true }).first().fill('Новый SEO сайта')
  const saved = page.waitForResponse((response) => response.url().endsWith('/v1/settings') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  expect((await saved).ok()).toBe(true)
  await expect(page.getByRole('button', { name: 'Сохранить', exact: true })).toBeEnabled()
  await page.goto('/admin/settings/covers')
  await page.getByRole('button', { name: 'Обновить три превью' }).click()
  await expect(page.locator('figure img')).toHaveCount(3)
  await expect(page.locator('figure img').last()).toHaveAttribute('width', '1074')
  await page.goto('/')
  await expect(page).toHaveTitle('Новый SEO сайта')
})
