import { expect, test } from '@playwright/test'
import { fileURLToPath } from 'node:url'

const fixture = (name: string) => fileURLToPath(new URL(`./fixtures/gallery/${name}.png`, import.meta.url))

test('галерея сохраняет снимки, порядок и подпись; открывается в статье и ленте', async ({ page }, test_info) => {
  test.setTimeout(120_000)
  await page.addInitScript(() => {
    localStorage.setItem('mock_viewer', 'member')
    sessionStorage.setItem('mock_media_url', `${location.origin}/tests/e2e/fixtures/gallery/landscape.png`)
  })
  await page.goto('/write')
  await expect(page.locator('[data-editor="ready"]')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('textbox', { name: 'Заголовок', exact: true }).fill('Галерея путешествия')
  await page.locator('.ce-paragraph').first().click()
  await page.locator('.ce-toolbar__plus').click()
  await page.locator('.ce-popover-item').filter({ hasText: 'Галерея' }).click()
  const editor = page.locator('.gallery-editor')
  await expect(editor).toBeVisible()
  const chooser = page.waitForEvent('filechooser')
  await editor.getByRole('button', { name: 'Добавить изображения' }).click()
  await (await chooser).setFiles([fixture('portrait'), fixture('landscape'), fixture('square')])
  await expect(editor.locator('.gallery-editor__item')).toHaveCount(3)
  await expect(editor.getByRole('status')).toHaveCount(0)
  await editor.getByRole('textbox', { name: 'Подпись галереи' }).fill('Несколько кадров из поездки')
  if (test_info.project.name.startsWith('wide')) {
    await editor.locator('.gallery-editor__drag').first().dragTo(editor.locator('.gallery-editor__item').nth(1))
  } else {
    await editor.getByRole('button', { name: 'Переместить вправо' }).first().click()
  }
  await expect(editor.locator('.gallery-editor__item img').first()).toHaveAttribute('width', '640')
  await editor.getByRole('button', { name: 'Удалить изображение' }).nth(1).click()
  await expect(editor.locator('.gallery-editor__item')).toHaveCount(2)
  await editor.locator('input[type=file]').setInputFiles(fixture('portrait'))
  await expect(editor.locator('.gallery-editor__item')).toHaveCount(3)

  await page.getByRole('button', { name: 'Параметры статьи' }).click()
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page).toHaveURL(/\/write\/[0-9a-f-]{36}$/)
  const write_url = page.url()
  await page.reload()
  await expect(page.locator('[data-editor="ready"]')).toBeVisible({ timeout: 60_000 })
  await expect(editor.locator('.gallery-editor__item img')).toHaveCount(3)
  await expect(editor.locator('.gallery-editor__item img').first()).toHaveAttribute('width', '640')
  await expect(editor.getByRole('textbox', { name: 'Подпись галереи' })).toHaveValue('Несколько кадров из поездки')
  const published = page.waitForResponse((response) => response.url().endsWith('/publish') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Опубликовать' }).click()
  expect((await published).ok()).toBe(true)
  await page.goto('/')
  const card = page.getByRole('article').filter({ has: page.getByRole('link', { name: 'Галерея путешествия', exact: true }) })
  await expect(card.locator('.image-gallery')).toBeVisible()
  await card.getByRole('link', { name: 'Галерея путешествия', exact: true }).click()
  if (test_info.project.name === 'wide-light') {
    await page.getByRole('link', { name: 'Тёмная тема', exact: true }).click()
    await page.getByRole('menuitemradio', { name: 'Светлая', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  }
  const gallery = page.locator('.image-gallery')
  await expect(gallery).toBeVisible()
  await expect.poll(() => gallery.locator('img').first().evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await expect(gallery.locator('figcaption')).toHaveText('Несколько кадров из поездки')
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.locator('body').evaluate((body) => body.clientWidth))
  const rail = gallery.locator('.gallery__rail')
  const bounds = await rail.boundingBox()
  if (!bounds) throw new Error('Gallery is missing')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 - 100, bounds.y + bounds.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => rail.evaluate((node) => node.scrollLeft)).toBeGreaterThan(50)
  await expect(page.getByRole('dialog', { name: 'Галерея', exact: true })).toHaveCount(0)
  await rail.evaluate((node) => { node.scrollLeft = 0 })
  await gallery.getByRole('button', { name: 'Следующее изображение' }).click()
  await expect.poll(() => rail.evaluate((node) => node.scrollLeft)).toBeGreaterThan(0)
  await rail.evaluate((node) => { node.scrollLeft = 0 })
  await gallery.getByRole('button', { name: 'Открыть изображение 1', exact: true }).click()
  const viewer = page.getByRole('dialog', { name: 'Галерея', exact: true })
  await expect(viewer).toBeVisible()
  await expect(viewer).toHaveCSS('background-color', 'rgb(16, 16, 16)')
  await expect.poll(() => viewer.locator('img').evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await expect(viewer.getByText('1 из 3')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(viewer.getByText('2 из 3')).toBeVisible()
  await viewer.locator('.gallery-lightbox__content').evaluate((node) => {
    node.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [new Touch({ identifier: 1, target: node, clientX: 280 })] }))
    node.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [new Touch({ identifier: 1, target: node, clientX: 80 })] }))
  })
  await expect(viewer.getByText('3 из 3')).toBeVisible()
  await page.screenshot({ path: test_info.outputPath('gallery-viewer.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await expect(gallery.getByRole('button', { name: 'Открыть изображение 1', exact: true })).toBeFocused()
  await page.screenshot({ path: test_info.outputPath('article-gallery.png'), fullPage: true, animations: 'disabled' })
  await page.goto(write_url)
  await expect(editor.locator('.gallery-editor__item')).toHaveCount(3)
})
