import { expect, test } from '@playwright/test'

test('приветственный контент: создание, предпросмотр, правка и удаление', async ({ page }) => {
  test.setTimeout(120_000)
  await page.addInitScript(() => localStorage.setItem('mock_viewer', 'superadmin'))
  await page.goto('/admin/settings')
  await page.getByRole('button', { name: 'Создать приветственный контент' }).click()
  await expect(page.locator('[data-editor="ready"]')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('textbox', { name: 'Заголовок', exact: true }).fill('Добро пожаловать')
  await page.locator('.ce-paragraph').first().click()
  await page.keyboard.type('Рады видеть вас в нашем блоге')
  await page.getByRole('button', { name: 'Предпросмотр', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Добро пожаловать' })).toBeVisible()
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByText('Добро пожаловать', { exact: true })).toBeVisible()
  await expect(page.getByText('Рады видеть вас в нашем блоге', { exact: true })).toBeVisible()
  await page.goto('/admin/settings')
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click()
  await expect(page.locator('[data-editor="ready"]')).toBeVisible()
  await page.getByRole('textbox', { name: 'Заголовок', exact: true }).fill('Наш блог')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByText('Наш блог', { exact: true })).toBeVisible()
  await page.goto('/admin/settings')
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click()
  await expect(page.locator('[data-editor="ready"]')).toBeVisible()
  await page.getByRole('button', { name: 'Удалить приветственный контент' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByText('Наш блог', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Рады видеть вас в нашем блоге', { exact: true })).toHaveCount(0)
})
